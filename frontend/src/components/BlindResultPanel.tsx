import { useEffect, useState } from 'react';
import type { LucideIcon } from 'lucide-react';
import {
  ShieldCheck, Eye, Cpu, Scissors, FileDown, Loader2, HelpCircle, Layers, Flame,
} from 'lucide-react';
import type { BlindDetectionResult, Verdict } from '../types';
import ConfidenceBar from './ConfidenceBar';
import Reveal from './Reveal';
import { useCountUp } from '../hooks/useCountUp';
import { downloadBlindReport, type BlindDetectionOptions } from '../api/detection';

const API_BASE = import.meta.env.VITE_API_URL || 'http://localhost:8000';

const FORGERY_LABELS: Record<string, string> = {
  spectral_anomaly: 'Spectral 1/f deviation',
  gan_upsampling: 'GAN upsampling artifact',
  noise_inconsistency: 'Noise inconsistency',
  texture_boundary: 'Texture boundary anomaly',
  edge_sharpness: 'Edge / gradient anomaly',
  compression_inconsistency: 'Compression (ELA) anomaly',
  none: 'None',
};

const ABSTAIN_REASONS: Record<string, string> = {
  low_confidence: 'no class reached a decisive score',
  member_disagreement: 'the models disagreed — the image may be unlike anything in training',
  below_user_threshold: 'confidence fell below the threshold you set',
  heuristics_only: 'no trained model is loaded, so only weak forensic heuristics were available',
  forensic_evidence_degraded_by_compression:
    'heavy re-compression destroyed the fine detail this analysis reads — a number here would be guesswork',
};

const CLASS_CONFIG: Record<Verdict, {
  label: string; icon: LucideIcon; ring: string; text: string; bg: string; border: string; desc: string;
}> = {
  UNCERTAIN: {
    label: 'UNCERTAIN', icon: HelpCircle,
    ring: '#fbbf24', text: 'text-amber-300', bg: 'bg-amber-500/10', border: 'border-amber-500/30',
    desc: 'The system is declining to commit. Treat this as “needs human review”, not as evidence either way.',
  },
  REAL: {
    label: 'REAL', icon: ShieldCheck,
    ring: '#34d399', text: 'text-emerald-300', bg: 'bg-emerald-500/10', border: 'border-emerald-500/30',
    desc: 'Natural image characteristics. No manipulation signature detected.',
  },
  AI_GENERATED: {
    label: 'AI GENERATED', icon: Cpu,
    ring: '#fb7185', text: 'text-rose-300', bg: 'bg-rose-500/10', border: 'border-rose-500/30',
    desc: 'Appears synthetically generated by a GAN or diffusion model.',
  },
  EDITED: {
    label: 'EDITED / TAMPERED', icon: Scissors,
    ring: '#fb923c', text: 'text-orange-300', bg: 'bg-orange-500/10', border: 'border-orange-500/30',
    desc: 'Shows signs of editing, splicing, or copy-move manipulation.',
  },
};

/** SVG ring that sweeps to the confidence value via stroke-dashoffset. */
function ConfidenceRing({ value, color }: { value: number; color: string }) {
  const pct = useCountUp(Math.round(value * 100), 1400);
  const [offset, setOffset] = useState(1);
  const radius = 34;
  const circumference = 2 * Math.PI * radius;

  useEffect(() => {
    const id = window.setTimeout(() => setOffset(1 - value), 120);
    return () => window.clearTimeout(id);
  }, [value]);

  return (
    <div className="relative flex h-[84px] w-[84px] flex-shrink-0 items-center justify-center">
      <svg className="absolute inset-0 -rotate-90" viewBox="0 0 84 84">
        <circle cx="42" cy="42" r={radius} fill="none" stroke="rgba(255,255,255,.07)" strokeWidth="5" />
        <circle
          cx="42" cy="42" r={radius} fill="none"
          stroke={color} strokeWidth="5" strokeLinecap="round"
          strokeDasharray={circumference}
          strokeDashoffset={circumference * offset}
          style={{ transition: 'stroke-dashoffset 1.4s cubic-bezier(.22,1,.36,1)' }}
        />
      </svg>
      <div className="text-center">
        <span className="block font-mono text-lg font-bold tabular-nums text-white">{pct}</span>
        <span className="block font-mono text-[9px] uppercase tracking-widest text-slate-500">conf</span>
      </div>
    </div>
  );
}

interface Props {
  result: BlindDetectionResult;
  imageFile: File;
  reportOptions?: BlindDetectionOptions;
}

export default function BlindResultPanel({ result, imageFile, reportOptions }: Props) {
  const cfg = CLASS_CONFIG[result.prediction];
  const Icon = cfg.icon;
  const forgeryLabel = FORGERY_LABELS[result.forgery_type] ?? result.forgery_type;
  const isFake = result.prediction !== 'REAL';
  const [downloading, setDownloading] = useState(false);
  const [previewUrl, setPreviewUrl] = useState<string | null>(null);

  useEffect(() => {
    const url = URL.createObjectURL(imageFile);
    setPreviewUrl(url);
    return () => URL.revokeObjectURL(url);
  }, [imageFile]);

  const handleDownloadReport = async () => {
    setDownloading(true);
    try {
      const blob = await downloadBlindReport(imageFile, reportOptions);
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = 'fakeguard_report.pdf';
      a.click();
      URL.revokeObjectURL(url);
    } finally {
      setDownloading(false);
    }
  };

  const signals: { label: string; value: number; color: 'blue' | 'red' | 'yellow' | 'purple' | 'green' | 'cyan' }[] = [
    { label: 'Spectral decay (1/f deviation)', value: result.analysis.fft_score, color: 'blue' },
    { label: 'GAN periodic artifacts', value: result.analysis.gan_score, color: 'red' },
    { label: 'Noise inconsistency', value: result.analysis.noise_score, color: 'yellow' },
    { label: 'Texture uniformity', value: result.analysis.texture_score, color: 'purple' },
    { label: 'Edge / gradient uniformity', value: result.analysis.edge_score, color: 'green' },
    { label: 'Error level analysis (ELA)', value: result.analysis.ela_score, color: 'cyan' },
  ];

  return (
    <div className="space-y-5">
      {/* ---------- verdict ---------- */}
      <div className={`card card-lit noise animate-scale-in overflow-hidden border ${cfg.border}`}>
        <div className="flex flex-wrap items-start gap-5">
          <ConfidenceRing value={result.confidence} color={cfg.ring} />

          <div className="min-w-0 flex-1">
            <p className="label-mono">Verdict</p>
            <div className="mt-1 flex items-center gap-2.5">
              <span className={`flex h-8 w-8 items-center justify-center rounded-lg ${cfg.bg}`}>
                <Icon size={17} className={cfg.text} />
              </span>
              <h2 className={`font-display text-2xl font-bold tracking-tight sm:text-3xl ${cfg.text}`}>
                {cfg.label}
              </h2>
            </div>
            <p className="mt-2 text-sm leading-relaxed text-slate-400">{cfg.desc}</p>

            {result.abstained && (
              <div className="mt-3 space-y-1.5 rounded-xl border border-amber-500/20 bg-amber-500/[.07] p-3">
                <p className="text-xs text-slate-300">
                  Models leaned toward{' '}
                  <span className="font-semibold text-white">
                    {result.model_prediction.replace('_', ' ')}
                  </span>{' '}
                  at {Math.round(result.confidence * 100)}% — not enough to commit.
                </p>
                <ul className="space-y-0.5">
                  {result.abstain_reasons.map((r) => (
                    <li key={r} className="font-mono text-[11px] text-amber-300/90">
                      → {ABSTAIN_REASONS[r] ?? r}
                    </li>
                  ))}
                </ul>
              </div>
            )}

            {!result.abstained && !result.meets_threshold && (
              <p className="mt-2 font-mono text-[11px] text-amber-300">
                ⚠ Below your confidence threshold — verify manually.
              </p>
            )}

            {result.provenance && (
              <div className="mt-3 rounded-xl border border-slate-700/60 bg-slate-900/40 p-3">
                <p className="label-mono flex items-center gap-1.5">
                  <ShieldCheck size={11} className="text-cyan-400" />
                  Provenance &amp; container
                  {result.evidence_tier && (
                    <span className="ml-auto font-mono text-[10px] text-slate-500">
                      tier {result.evidence_tier.charAt(0)}
                    </span>
                  )}
                </p>
                <ul className="mt-1.5 space-y-1">
                  <li className="font-mono text-[11px] text-slate-400">
                    signed manifest (C2PA):{' '}
                    <span className={result.provenance.c2pa_verified ? 'text-emerald-300' : 'text-slate-500'}>
                      {result.provenance.c2pa_verified
                        ? 'verified'
                        : result.provenance.c2pa_manifest_present
                          ? 'present, unverified'
                          : 'none'}
                    </span>
                  </li>
                  <li className="font-mono text-[11px] text-slate-400">
                    camera capture evidence:{' '}
                    <span className="text-slate-300">{result.provenance.camera_evidence_strength}</span>
                  </li>
                  {result.provenance.generative_software_hint && (
                    <li className="font-mono text-[11px] text-violet-300">
                      metadata names a generative tool: {result.provenance.generative_software_hint}
                    </li>
                  )}
                </ul>
                {/*
                  Non-negotiable caveat, mirrored from the backend's own
                  invariant (models/provenance.py): missing provenance is NOT
                  evidence of AI generation. Most authentic photos have none —
                  any screenshot or social upload strips it. Showing the
                  "none" states above without this line would invite exactly
                  the wrong inference.
                */}
                {!result.provenance.c2pa_verified && (
                  <p className="mt-2 text-[10px] leading-relaxed text-slate-500">
                    Missing provenance is not evidence of AI generation — most authentic photos
                    carry none, and any screenshot or re-upload strips it.
                  </p>
                )}
              </div>
            )}

            {!result.abstained && result.forgery_type !== 'none' && (
              <p className="mt-2 flex items-center gap-1.5 font-mono text-[11px] text-slate-500">
                <Flame size={11} className="text-violet-400" />
                Primary signal:{' '}
                <span className="font-semibold text-violet-300">{forgeryLabel}</span>
              </p>
            )}
          </div>

          <button
            onClick={handleDownloadReport}
            disabled={downloading}
            className="btn-secondary flex-shrink-0 px-4 py-2.5 text-sm"
          >
            {downloading ? <Loader2 size={15} className="animate-spin" /> : <FileDown size={15} />}
            PDF
          </button>
        </div>
      </div>

      {/* ---------- class probabilities ---------- */}
      <Reveal>
        <div className="card space-y-3.5">
          <h3 className="label-mono">Class probabilities</h3>
          <ConfidenceBar label="Real" value={result.class_probabilities.REAL} color="green" delay={80} />
          <ConfidenceBar label="AI generated" value={result.class_probabilities.AI_GENERATED} color="red" delay={160} />
          <ConfidenceBar label="Edited / tampered" value={result.class_probabilities.EDITED} color="yellow" delay={240} />
        </div>
      </Reveal>

      {/* ---------- ensemble ---------- */}
      {result.ensemble && result.uncertainty && (
        <Reveal>
          <div className="card space-y-3.5">
            <h3 className="flex items-center gap-2 font-display font-bold text-white">
              <Layers size={16} className="text-violet-400" /> Model ensemble
            </h3>

            {result.member_probabilities && (
              <div className="space-y-2">
                {Object.entries(result.member_probabilities).map(([name, probs]) => {
                  const [topClass, topProb] = Object.entries(probs).sort((a, b) => b[1] - a[1])[0];
                  return (
                    <div
                      key={name}
                      className="flex items-center justify-between rounded-lg border border-white/[.06] bg-white/[.02] px-3 py-2"
                    >
                      <span className="font-mono text-[11px] text-slate-400">{name}</span>
                      <span className="text-sm text-slate-200">
                        {topClass.replace('_', ' ')}{' '}
                        <span className="font-mono text-xs text-slate-500">
                          {Math.round(topProb * 100)}%
                        </span>
                      </span>
                    </div>
                  );
                })}
              </div>
            )}

            <div className="divider" />

            <div className="grid grid-cols-2 gap-3">
              {[
                { k: 'Epistemic', v: result.uncertainty.epistemic, hint: 'disagreement / novelty' },
                { k: 'Aleatoric', v: result.uncertainty.aleatoric, hint: 'genuine ambiguity' },
              ].map(({ k, v, hint }) => (
                <div key={k} className="rounded-xl border border-white/[.06] bg-white/[.02] p-3">
                  <p className="font-mono text-[10px] uppercase tracking-wider text-slate-500">{k}</p>
                  <p className="mt-0.5 font-mono text-lg font-bold tabular-nums text-white">
                    {v.toFixed(3)}
                  </p>
                  <p className="font-mono text-[9px] text-slate-600">{hint}</p>
                </div>
              ))}
            </div>

            <div className="flex flex-wrap items-center gap-x-4 gap-y-1 font-mono text-[10px] text-slate-600">
              <span className={result.ensemble.members_agree ? 'text-emerald-400' : 'text-amber-400'}>
                models {result.ensemble.members_agree ? 'agree' : 'disagree'}
              </span>
              <span>TTA {result.ensemble.tta_used ? 'on' : 'off'}</span>
              <span>calibration T={result.ensemble.temperature.toFixed(3)}</span>
            </div>
          </div>
        </Reveal>
      )}

      {/* ---------- forensic signals ---------- */}
      <Reveal>
        <div className="card space-y-3.5">
          <h3 className="flex items-center gap-2 font-display font-bold text-white">
            <Eye size={16} className="text-cyan-400" /> Forensic signals
          </h3>
          {signals.map((s, i) => (
            <ConfidenceBar key={s.label} label={s.label} value={s.value} color={s.color} delay={i * 70} />
          ))}
          {result.signal_agreement !== null && (
            <p className="pt-1 font-mono text-[10px] text-slate-600">
              CNN and heuristic signals{' '}
              <span className={result.signal_agreement ? 'text-emerald-400' : 'text-amber-400'}>
                {result.signal_agreement ? 'agree' : 'disagree'}
              </span>{' '}
              on this verdict.
            </p>
          )}
        </div>
      </Reveal>

      {/* ---------- image + heatmap ---------- */}
      <Reveal>
        <div className="grid gap-4 md:grid-cols-2">
          <div className="card space-y-3">
            <p className="label-mono">Uploaded image</p>
            {previewUrl && (
              <img
                src={previewUrl}
                alt="uploaded"
                className="max-h-64 w-full rounded-xl object-contain"
              />
            )}
          </div>

          {result.heatmap_url ? (
            <div className="card space-y-3">
              <p className="label-mono flex items-center gap-1.5">
                <Flame size={11} className="text-orange-400" /> Anomaly heatmap
              </p>
              <img
                src={`${API_BASE}${result.heatmap_url}`}
                alt="heatmap"
                className="max-h-64 w-full rounded-xl object-contain"
              />
            </div>
          ) : (
            <div className="card flex min-h-32 items-center justify-center border-dashed text-center font-mono text-[11px] leading-relaxed text-slate-600">
              {!isFake
                ? 'No heatmap — image classified as real'
                : reportOptions?.enableGradcam === false
                  ? 'Grad-CAM disabled in settings'
                  : 'Heatmap generation failed'}
            </div>
          )}
        </div>
      </Reveal>
    </div>
  );
}
