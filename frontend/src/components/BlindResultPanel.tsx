import { useState } from 'react';
import type { LucideIcon } from 'lucide-react';
import { CheckCircle, Eye, Cpu, Scissors, FileDown, Loader2, HelpCircle, Layers } from 'lucide-react';
import type { BlindDetectionResult, Verdict } from '../types';
import ConfidenceBar from './ConfidenceBar';
import { downloadBlindReport, type BlindDetectionOptions } from '../api/detection';

const API_BASE = import.meta.env.VITE_API_URL || 'http://localhost:8000';

const FORGERY_LABELS: Record<string, string> = {
  spectral_anomaly:     'Spectral 1/f Deviation',
  gan_upsampling:       'GAN Upsampling Artifact',
  noise_inconsistency:  'Noise Inconsistency',
  texture_boundary:     'Texture Boundary Anomaly',
  edge_sharpness:       'Edge/Gradient Anomaly',
  compression_inconsistency: 'Compression (ELA) Anomaly',
  none:                 'None',
};

const ABSTAIN_REASONS: Record<string, string> = {
  low_confidence: 'no class reached a decisive score',
  member_disagreement: 'the two models disagreed — the image may be unlike anything in training',
  below_user_threshold: 'confidence fell below the threshold you set',
  heuristics_only: 'no trained model is loaded, so only weak forensic heuristics were available',
};

const CLASS_CONFIG: Record<Verdict, {
  label: string;
  color: string;
  bgColor: string;
  borderColor: string;
  icon: LucideIcon;
  desc: string;
}> = {
  UNCERTAIN: {
    label: 'UNCERTAIN',
    color: 'text-yellow-400',
    bgColor: 'bg-yellow-900/30',
    borderColor: 'border-yellow-700/50',
    icon: HelpCircle,
    desc: 'The system is declining to commit to a verdict. Treat this as "needs human review", not as evidence either way.',
  },
  REAL: {
    label: 'REAL',
    color: 'text-green-400',
    bgColor: 'bg-green-900/30',
    borderColor: 'border-green-700/50',
    icon: CheckCircle,
    desc: 'Image shows natural characteristics. No manipulation detected.',
  },
  AI_GENERATED: {
    label: 'AI GENERATED',
    color: 'text-red-400',
    bgColor: 'bg-red-900/30',
    borderColor: 'border-red-700/50',
    icon: Cpu,
    desc: 'Image appears to be synthetically generated by a GAN or diffusion model.',
  },
  EDITED: {
    label: 'EDITED / TAMPERED',
    color: 'text-orange-400',
    bgColor: 'bg-orange-900/30',
    borderColor: 'border-orange-700/50',
    icon: Scissors,
    desc: 'Image shows signs of photo editing, splicing, or copy-move manipulation.',
  },
};

interface Props {
  result: BlindDetectionResult;
  imageFile: File;
  reportOptions?: BlindDetectionOptions;
}

export default function BlindResultPanel({ result, imageFile, reportOptions }: Props) {
  const cfg = CLASS_CONFIG[result.prediction];
  const Icon = cfg.icon;
  const previewUrl = URL.createObjectURL(imageFile);
  const forgeryLabel = FORGERY_LABELS[result.forgery_type] ?? result.forgery_type;
  const isFake = result.prediction !== 'REAL';
  const [downloading, setDownloading] = useState(false);

  const handleDownloadReport = async () => {
    setDownloading(true);
    try {
      const blob = await downloadBlindReport(imageFile, reportOptions);
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = 'fakeguard_report.pdf';
      a.click();
      URL.revokeObjectURL(url);
    } finally {
      setDownloading(false);
    }
  };

  return (
    <div className="space-y-5 animate-in fade-in duration-500">
      {/* Verdict */}
      <div className={`card glow-purple flex items-center gap-4 border ${cfg.borderColor}`}>
        <div className={`w-16 h-16 rounded-2xl flex items-center justify-center flex-shrink-0 ${cfg.bgColor}`}>
          <Icon size={32} className={cfg.color} />
        </div>
        <div className="flex-1 min-w-0">
          <p className="text-sm text-slate-400 uppercase tracking-widest font-medium">Verdict</p>
          <p className={`text-3xl font-bold ${cfg.color}`}>{cfg.label}</p>
          <p className="text-slate-400 text-sm mt-0.5">{cfg.desc}</p>

          {result.abstained && (
            <div className="mt-2 space-y-1">
              <p className="text-xs text-slate-300">
                Models leaned toward{' '}
                <span className="font-semibold text-slate-100">
                  {result.model_prediction.replace('_', ' ')}
                </span>{' '}
                at {Math.round(result.confidence * 100)}% — not enough to commit.
              </p>
              <ul className="text-xs text-yellow-400/90 space-y-0.5">
                {result.abstain_reasons.map((reason) => (
                  <li key={reason}>• {ABSTAIN_REASONS[reason] ?? reason}</li>
                ))}
              </ul>
            </div>
          )}

          {!result.abstained && !result.meets_threshold && (
            <p className="text-yellow-400 text-xs font-semibold mt-1">
              ⚠ Below your confidence threshold — verify manually.
            </p>
          )}

          {!result.abstained && (
            <p className="text-slate-400 text-xs mt-1">
              Confidence:{' '}
              <span className="text-slate-200 font-semibold">
                {Math.round(result.confidence * 100)}%
              </span>
              {result.forgery_type !== 'none' && (
                <>
                  {' '}· Primary signal:{' '}
                  <span className="text-purple-400 font-semibold">{forgeryLabel}</span>
                </>
              )}
            </p>
          )}
        </div>
        <button
          onClick={handleDownloadReport}
          disabled={downloading}
          className="btn-secondary flex-shrink-0 text-sm"
        >
          {downloading ? (
            <Loader2 size={16} className="animate-spin" />
          ) : (
            <FileDown size={16} />
          )}
          PDF Report
        </button>
      </div>

      {/* Ensemble + uncertainty */}
      {result.ensemble && result.uncertainty && (
        <div className="card space-y-3">
          <h3 className="font-semibold text-slate-200 flex items-center gap-2">
            <Layers size={16} className="text-purple-400" /> Model Ensemble
          </h3>

          {result.member_probabilities && (
            <div className="space-y-2">
              {Object.entries(result.member_probabilities).map(([name, probs]) => {
                const top = Object.entries(probs).sort((a, b) => b[1] - a[1])[0];
                return (
                  <div key={name} className="flex items-center justify-between text-sm">
                    <span className="text-slate-400 font-mono text-xs">{name}</span>
                    <span className="text-slate-200">
                      {top[0].replace('_', ' ')}{' '}
                      <span className="text-slate-500">{Math.round(top[1] * 100)}%</span>
                    </span>
                  </div>
                );
              })}
            </div>
          )}

          <div className="border-t border-dark-300 pt-3 space-y-1.5 text-xs">
            <div className="flex justify-between">
              <span className="text-slate-400">Models agree</span>
              <span className={result.ensemble.members_agree ? 'text-green-400' : 'text-yellow-400'}>
                {result.ensemble.members_agree ? 'yes' : 'no'}
              </span>
            </div>
            <div className="flex justify-between">
              <span className="text-slate-400">
                Epistemic uncertainty
                <span className="text-slate-600"> (disagreement / novelty)</span>
              </span>
              <span className="text-slate-200 font-mono">
                {result.uncertainty.epistemic.toFixed(3)}
              </span>
            </div>
            <div className="flex justify-between">
              <span className="text-slate-400">
                Aleatoric uncertainty
                <span className="text-slate-600"> (genuine ambiguity)</span>
              </span>
              <span className="text-slate-200 font-mono">
                {result.uncertainty.aleatoric.toFixed(3)}
              </span>
            </div>
            <div className="flex justify-between text-slate-600">
              <span>
                {result.ensemble.tta_used ? 'TTA on' : 'TTA off'} · calibration T=
                {result.ensemble.temperature.toFixed(3)}
              </span>
            </div>
          </div>
        </div>
      )}

      {/* Class Probability Breakdown */}
      <div className="card space-y-3">
        <h3 className="font-semibold text-slate-200 text-sm uppercase tracking-wider">
          Class Probabilities
        </h3>
        <ConfidenceBar
          label="Real"
          value={result.class_probabilities.REAL}
          color="green"
        />
        <ConfidenceBar
          label="AI Generated"
          value={result.class_probabilities.AI_GENERATED}
          color="red"
        />
        <ConfidenceBar
          label="Edited / Tampered"
          value={result.class_probabilities.EDITED}
          color="yellow"
        />
      </div>

      {/* Signal Analysis */}
      <div className="card space-y-3">
        <h3 className="font-semibold text-slate-200 flex items-center gap-2">
          <Eye size={16} className="text-purple-400" /> Signal Analysis
        </h3>
        <ConfidenceBar
          label="Spectral Decay (1/f deviation)"
          value={result.analysis.fft_score}
          color="blue"
        />
        <ConfidenceBar
          label="GAN Periodic Artifacts"
          value={result.analysis.gan_score}
          color="red"
        />
        <ConfidenceBar
          label="Noise Inconsistency"
          value={result.analysis.noise_score}
          color="yellow"
        />
        <ConfidenceBar
          label="Texture Uniformity"
          value={result.analysis.texture_score}
          color="purple"
        />
        <ConfidenceBar
          label="Edge / Gradient Uniformity"
          value={result.analysis.edge_score}
          color="green"
        />
        <ConfidenceBar
          label="Error Level Analysis (ELA)"
          value={result.analysis.ela_score}
          color="blue"
        />
        {result.signal_agreement !== null && (
          <p className="text-xs text-slate-500 pt-1">
            CNN and heuristic signals{' '}
            <span className={result.signal_agreement ? 'text-green-400' : 'text-yellow-400'}>
              {result.signal_agreement ? 'agree' : 'disagree'}
            </span>{' '}
            on this verdict.
          </p>
        )}
      </div>

      {/* Image + Heatmap */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
        <div className="card space-y-3">
          <p className="text-sm font-medium text-slate-400">Uploaded Image</p>
          <img
            src={previewUrl}
            alt="uploaded"
            className="w-full rounded-xl object-contain max-h-64"
          />
        </div>

        {result.heatmap_url ? (
          <div className="card space-y-3">
            <p className="text-sm font-medium text-slate-400">Anomaly Heatmap</p>
            <img
              src={`${API_BASE}${result.heatmap_url}`}
              alt="heatmap"
              className="w-full rounded-xl object-contain max-h-64"
            />
          </div>
        ) : (
          <div className="card flex items-center justify-center text-slate-600 text-sm h-full min-h-32 border-dashed">
            {!isFake
              ? 'No heatmap (image classified as real)'
              : reportOptions?.enableGradcam === false
                ? 'Grad-CAM disabled in settings'
                : 'Heatmap generation failed'}
          </div>
        )}
      </div>
    </div>
  );
}
